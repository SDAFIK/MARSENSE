import { test, expect } from "@playwright/test";
test("authenticated isolated showcase: login, replay, decision, inheritance, reset", async ({ page }, testInfo) => {
  await page.goto("/login");
  await page.getByLabel("Username",{exact:true}).fill("showcase-admin");
  await page.getByLabel("Password",{exact:true}).fill("isolated-showcase-test-password");
  await page.getByRole("button",{name:"Sign in",exact:true}).click();
  await expect(page).toHaveURL(/\/mission$/);
  await expect(page.getByRole("tab",{name:"EXPECT",exact:true})).toBeVisible();
  await page.getByRole("tab",{name:"OBSERVE",exact:true}).click();
  await expect(page.getByLabel("Demonstration observation")).toBeVisible();
  await expect(page.getByLabel("Upload ground image")).toHaveCount(0);
  await page.getByRole("button",{name:"Analyze terrain"}).click();
  await expect(page.getByRole("tabpanel")).toContainText("Significant Difference");
  await page.getByRole("tab",{name:"VERIFY",exact:true}).click();
  await page.getByRole("button",{name:"Confirm observation",exact:true}).click();
  await expect(page.getByRole("heading",{name:"Route Beta",exact:true})).toBeVisible();
  await page.screenshot({path:testInfo.outputPath("showcase-confirmed.png"),fullPage:true});
  await page.getByLabel("Active mission").selectOption("eva-02");
  await expect(page.getByText("INHERITED FROM EVA-01",{exact:false})).toBeVisible();
  await page.reload();
  await expect(page.getByText("INHERITED FROM EVA-01",{exact:false})).toBeVisible();
  await page.locator("summary").filter({hasText:"Showcase Admin"}).click();
  page.once("dialog",d=>d.accept());
  await page.getByRole("button",{name:"Reset showcase"}).click();
  await expect(page.getByLabel("Active mission")).toHaveValue("eva-01");
  await expect(page.getByRole("complementary",{name:"Mission trace and evidence"})).toContainText("Route Alpha");
  await page.getByRole("tab",{name:"OBSERVE",exact:true}).click();
  await page.getByRole("button",{name:"Analyze terrain"}).click();
  await expect(page.getByRole("tabpanel")).toContainText("Significant Difference");
});
